package com.circles.health.patient.response;

public class AnalyticsExitAndBlogPageDetails {
	private String pagePath;
	private String pageCount;
	private String category;
	private Integer pageExitProfileCount;

	public String getPagePath() {
		return pagePath;
	}
	public void setPagePath(String pagePath) {
		this.pagePath = pagePath;
	}
	public String getPageCount() {
		return pageCount;
	}
	public void setPageCount(String pageCount) {
		this.pageCount = pageCount;
	}
	public String getCategory() {
		return category;
	}
	public void setCategory(String category) {
		this.category = category;
	}
	public Integer getPageExitProfileCount() {
		return pageExitProfileCount;
	}
	public void setPageExitProfileCount(Integer pageExitProfileCount) {
		this.pageExitProfileCount = pageExitProfileCount;
	}
	

}
